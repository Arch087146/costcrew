//! Terminal table + shareable markdown report.

use crate::scan::Row;

pub const RESET: &str = "\x1b[0m";
pub const DIM: &str = "\x1b[2m";
pub const BOLD: &str = "\x1b[1m";
pub const CYAN: &str = "\x1b[36m";
pub const YELLOW: &str = "\x1b[33m";
pub const GREEN: &str = "\x1b[32m";
pub const RED: &str = "\x1b[31m";

pub struct Totals {
    pub total_cost: f64,
    pub total_requests: u64,
    pub unknown_models: usize,
}

pub fn print_table(rows: &[Row], since_days: u32, totals: &Totals) {
    let period = if since_days == 1 {
        "last 24h".to_string()
    } else {
        format!("last {since_days}d")
    };

    println!();
    println!("  {BOLD}costcrew{RESET} {DIM}· AI agent spend · {period}{RESET}");
    println!();

    let widths = col_widths(rows);
    let cost_w = 10;

    // header
    print!("  ");
    for (i, h) in [
        "provider",
        "model",
        "reqs",
        "tokens in",
        "tokens out",
        "cache",
    ]
    .iter()
    .enumerate()
    {
        print!("{DIM}{:>width$}{RESET}  ", h, width = widths[i]);
    }
    println!("{DIM}{:>width$}{RESET}", "cost (usd)", width = cost_w);

    // separator
    print!("  ");
    for w in &widths {
        print!("{DIM}{}{RESET}  ", "-".repeat(*w));
    }
    println!("{DIM}{}{RESET}", "-".repeat(cost_w));

    // rows
    for r in rows {
        print!("  ");
        print!("{:>w$}  ", r.provider, w = widths[0]);
        print!("{:>w$}  ", truncate(&r.model, widths[1]), w = widths[1]);
        print!("{:>w$}  ", r.requests, w = widths[2]);
        print!("{:>w$}  ", r.input_tokens, w = widths[3]);
        print!("{:>w$}  ", r.output_tokens, w = widths[4]);
        print!("{:>w$}  ", r.cache_tokens, w = widths[5]);
        if r.known_price {
            let color = cost_color(r.cost);
            print!("{}{:>10.4}{}", color, r.cost, RESET);
        } else {
            print!("{:>10}", "?");
        }
        println!();
    }

    // totals
    let t_in: u64 = rows.iter().map(|r| r.input_tokens).sum();
    let t_out: u64 = rows.iter().map(|r| r.output_tokens).sum();
    let t_cache: u64 = rows.iter().map(|r| r.cache_tokens).sum();
    print!("  ");
    for w in &widths[..2] {
        print!("{DIM}{}{RESET}  ", "-".repeat(*w));
    }
    print!("{BOLD}total{RESET}  ");
    print!("{:>w$}  ", "", w = widths[2] + 1);
    print!("{:>w$}  ", t_in, w = widths[3] + 1);
    print!("{:>w$}  ", t_out, w = widths[4] + 1);
    print!("{:>w$}  ", t_cache, w = widths[5] + 1);
    // -0.0 guard: an all-unpriced table shouldn't render as negative money
    let shown = if totals.total_cost.abs() < 0.000_1 {
        0.0
    } else {
        totals.total_cost
    };
    println!("{BOLD}{GREEN}${:>8.2}{RESET}", shown);
    println!();

    // bar chart of spend share
    let max = rows.iter().map(|r| r.cost).fold(0.0_f64, f64::max);
    if max > 0.0 {
        for r in rows.iter().filter(|r| r.known_price) {
            let scale = ((r.cost / max) * 24.0).round() as usize;
            let units = if r.cost > 0.0 { scale.max(1) } else { 0 };
            let bar: String = std::iter::repeat('#').take(units).collect();
            let color = cost_color(r.cost);
            println!(
                "  {:>26} {color}{bar}{RESET} ${:.2}",
                truncate(&r.model, 26),
                r.cost
            );
        }
        println!();
    }

    if totals.unknown_models > 0 {
        println!(
            "  {DIM}{} model(s) not priced yet — saw them, didn't bill them.{RESET}",
            totals.unknown_models
        );
    }
}

fn cost_color(cost: f64) -> &'static str {
    if cost < 1.0 {
        GREEN
    } else if cost < 10.0 {
        YELLOW
    } else {
        RED
    }
}

fn truncate(s: &str, max: usize) -> String {
    if s.len() <= max {
        s.to_string()
    } else {
        format!("{}…", &s[..max.saturating_sub(1)])
    }
}

fn col_widths(rows: &[Row]) -> [usize; 6] {
    let mut w = [
        "provider".len(),
        "model".len(),
        "reqs".len(),
        "tokens in".len(),
        "tokens out".len(),
        "cache".len(),
    ];
    for r in rows {
        w[0] = w[0].max(r.provider.len());
        w[1] = w[1].max(r.model.len().min(40));
        w[2] = w[2].max(r.requests.to_string().len());
        w[3] = w[3].max(r.input_tokens.to_string().len());
        w[4] = w[4].max(r.output_tokens.to_string().len());
        w[5] = w[5].max(r.cache_tokens.to_string().len());
    }
    w
}

pub fn print_markdown(rows: &[Row], since_days: u32, totals: &Totals) {
    println!("# costcrew report");
    println!();
    println!(
        "AI agent spend, last {since_days} day(s). Generated by [costcrew](https://github.com/Arch087146/costcrew)."
    );
    println!();
    println!("| provider | model | reqs | tokens in | tokens out | cached | cost (USD) |");
    println!("|---|---|---:|---:|---:|---:|---:|");
    for r in rows {
        let cost = if r.known_price {
            format!("${:.4}", r.cost)
        } else {
            "?".to_string()
        };
        println!(
            "| {} | `{}` | {} | {} | {} | {} | {} |",
            r.provider, r.model, r.requests, r.input_tokens, r.output_tokens, r.cache_tokens, cost
        );
    }
    let t_in: u64 = rows.iter().map(|r| r.input_tokens).sum();
    let t_out: u64 = rows.iter().map(|r| r.output_tokens).sum();
    let t_cache: u64 = rows.iter().map(|r| r.cache_tokens).sum();
    println!(
        "| **total** | | **{}** | **{}** | **{}** | **{}** | **${:.2}** |",
        totals.total_requests, t_in, t_out, t_cache, totals.total_cost
    );
    if totals.unknown_models > 0 {
        println!();
        println!(
            "> {} model(s) had no price entry and were excluded from totals.",
            totals.unknown_models
        );
    }
}
